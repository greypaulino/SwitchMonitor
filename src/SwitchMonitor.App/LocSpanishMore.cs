    private static readonly (Regex Match, string Spanish)[] compiled = Compile();

    private static (Regex, string)[] Compile()
    {
        var list = new List<(Regex, string)>();
        foreach (var (english, spanish) in Raw)
        {
            string pattern = "^" + Regex.Escape(english).Replace(@"\{}", "(.+?)").Replace("{}", "(.+?)") + "$";
            list.Add((new Regex(pattern, RegexOptions.Singleline | RegexOptions.CultureInvariant), spanish));
        }
        return list.ToArray();
    }

    /// <summary>The Spanish of a text with a changing part, or null when no entry matches.</summary>
    public static string? Match(string english)
    {
        foreach (var (regex, spanish) in compiled)
        {
            var m = regex.Match(english);
            if (!m.Success) continue;
            string result = spanish;
            for (int i = 1; i < m.Groups.Count; i++) result = result.Replace("{" + (i - 1) + "}", Loc.T(m.Groups[i].Value));
            return result;
        }
        return null;
    }
